import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin } from 'vite';

export const SW_FILE = 'sw.js';

/**
 * Service worker source for a build. `files` are paths relative to the output directory; `version` changes whenever any
 * built file changes, which renames the cache and makes browsers install the new worker (old caches are deleted).
 *
 * - install: precache the app shell (with cache: 'reload' to bypass the HTTP cache)
 * - navigations: network first, cached shell when offline
 * - other same-scope GETs: cache first (built assets have content hashes)
 */
export function buildServiceWorker(files: readonly string[], version: string): string {
  const assets = [...new Set(['./', ...files.filter((f) => !f.endsWith('.map') && f !== SW_FILE).map((f) => `./${f}`)])].sort();
  return `/* Pacer Studio service worker - generated by build/pwa.ts, do not edit */
const CACHE = ${JSON.stringify(`pacer-studio-${version}`)};
const ASSETS = ${JSON.stringify(assets, null, 2)};
const scoped = (path) => new URL(path, self.registration.scope).href;

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(ASSETS.map((path) => new Request(scoped(path), { cache: 'reload' }))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('pacer-studio-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (!request.url.startsWith(self.registration.scope)) return;
  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request).catch(() =>
        caches.open(CACHE).then((cache) => cache.match(scoped('./')).then((hit) => hit || cache.match(scoped('./index.html')))),
      ),
    );
    return;
  }
  event.respondWith(
    caches.open(CACHE).then((cache) => cache.match(request, { ignoreSearch: true }).then((hit) => hit || fetch(request))),
  );
});
`;
}

function listFiles(dir: string, root = dir): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...listFiles(full, root));
    else out.push(relative(root, full).split(sep).join('/'));
  }
  return out.sort();
}

/** Writes sw.js into the build output after every production build. Not active in dev or tests. */
export function pwaPlugin(): Plugin {
  let outDir = '';
  return {
    name: 'pacer-studio-pwa',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const files = listFiles(outDir).filter((f) => !f.endsWith('.map') && f !== SW_FILE);
      const hash = createHash('sha256');
      for (const file of files) {
        hash.update(file);
        hash.update(readFileSync(join(outDir, file)));
      }
      writeFileSync(join(outDir, SW_FILE), buildServiceWorker(files, hash.digest('hex').slice(0, 16)));
    },
  };
}
